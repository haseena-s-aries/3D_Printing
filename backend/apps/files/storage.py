"""Storage backends for engineering files (originals and derivatives).

Keys are always generated by the server: tenants/{tenant_id}/{originals|derivatives}/{file_id}/v{n}/...
Objects are write-once: saving to an existing key fails (originals are never overwritten, CAD-005).

- LocalStorage: development and tests (filesystem, path containment enforced).
- AzureBlobStorage: production (Azure Blob Storage) and local testing with Azurite.
  One container per tenant ("t-" + tenant id without dashes) keeps tenants apart at the storage layer.
"""
import hashlib
import os
import uuid
from abc import ABC, abstractmethod
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import BinaryIO, Iterable

from django.conf import settings


class StorageError(Exception):
    pass


class ObjectExists(StorageError):
    pass


class Storage(ABC):
    @abstractmethod
    def save_new(self, key: str, chunks: Iterable[bytes]) -> tuple[int, str]:
        """Write a new object; return (size, sha256). Fails with ObjectExists if the key exists."""

    @abstractmethod
    def open(self, key: str) -> BinaryIO: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    def signed_url(self, key: str, filename: str, seconds: int, inline: bool = False, content_type: str | None = None) -> str | None:
        """Direct, time-limited URL if the backend supports it; None means stream through the API.
        `inline` serves the object for in-browser viewing instead of as a download."""
        return None


def validate_key(key: str) -> str:
    parts = key.split("/")
    if len(parts) < 4 or parts[0] != "tenants" or any(p in ("", ".", "..") for p in parts):
        raise StorageError(f"invalid storage key: {key!r}")
    uuid.UUID(parts[1])
    return key


class LocalStorage(Storage):
    def __init__(self, root: Path):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        p = (self.root / validate_key(key)).resolve()
        if self.root not in p.parents:
            raise StorageError("path escapes storage root")
        return p

    def save_new(self, key, chunks):
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + f".part-{uuid.uuid4().hex}")
        digest, size = hashlib.sha256(), 0
        try:
            with open(tmp, "xb") as fh:
                for chunk in chunks:
                    fh.write(chunk)
                    digest.update(chunk)
                    size += len(chunk)
            try:
                os.link(tmp, path)  # atomic and fails if the target exists
            except FileExistsError:
                raise ObjectExists(key)
        finally:
            tmp.unlink(missing_ok=True)
        return size, digest.hexdigest()

    def open(self, key):
        return open(self._path(key), "rb")

    def exists(self, key):
        return self._path(key).exists()


class AzureBlobStorage(Storage):
    def __init__(self, connection_string: str):
        from azure.storage.blob import BlobServiceClient

        self.connection_string = connection_string
        self.service = BlobServiceClient.from_connection_string(connection_string)

    @staticmethod
    def split(key: str) -> tuple[str, str]:
        parts = validate_key(key).split("/")
        container = "t-" + uuid.UUID(parts[1]).hex
        return container, "/".join(parts[2:])

    def _blob(self, key):
        container, name = self.split(key)
        return self.service.get_container_client(container), name

    def save_new(self, key, chunks):
        from azure.core.exceptions import ResourceExistsError

        container, name = self._blob(key)
        try:
            container.create_container()
        except ResourceExistsError:
            pass
        digest, size = hashlib.sha256(), 0

        def stream():
            nonlocal size
            for chunk in chunks:
                digest.update(chunk)
                size += len(chunk)
                yield chunk

        try:
            container.upload_blob(name, stream(), overwrite=False)
        except ResourceExistsError:
            raise ObjectExists(key)
        return size, digest.hexdigest()

    def open(self, key):
        import io

        container, name = self._blob(key)
        return io.BytesIO(container.download_blob(name).readall())

    def exists(self, key):
        container, name = self._blob(key)
        return container.get_blob_client(name).exists()

    def signed_url(self, key, filename, seconds, inline=False, content_type=None):
        """Read-only SAS for one blob. Uses the account key (Azurite / development).
        Production should use a user-delegation SAS with managed identity (see docs/architecture.md)."""
        from azure.storage.blob import BlobSasPermissions, generate_blob_sas

        container, name = self.split(key)
        client = self.service.get_blob_client(container, name)
        cred = self.service.credential
        if not getattr(cred, "account_key", None):
            return None
        sas = generate_blob_sas(
            account_name=client.account_name, container_name=container, blob_name=name,
            account_key=cred.account_key, permission=BlobSasPermissions(read=True),
            expiry=datetime.now(timezone.utc) + timedelta(seconds=seconds),
            content_disposition=f'{"inline" if inline else "attachment"}; filename="{filename}"',
            content_type=content_type if inline else None,
        )
        return f"{client.url}?{sas}"


_storage: Storage | None = None


def get_storage() -> Storage:
    global _storage
    if _storage is None:
        if settings.FILE_STORAGE_BACKEND == "azure":
            _storage = AzureBlobStorage(settings.AZURE_STORAGE_CONNECTION_STRING)
        else:
            _storage = LocalStorage(settings.LOCAL_STORAGE_ROOT)
    return _storage


def reset_storage_cache():
    global _storage
    _storage = None


def original_key(tenant_id, file_id, version: int, ext: str) -> str:
    return f"tenants/{tenant_id}/originals/{file_id}/v{version}/original.{ext}"


def derivative_key(tenant_id, file_id, version: int, kind: str) -> str:
    return f"tenants/{tenant_id}/derivatives/{file_id}/v{version}/derivative.{kind}"
